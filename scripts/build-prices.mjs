const [, ...rows] = readFileSync(SOURCE, 'utf8').trim().split(/\r?\n/);
const prices = {};

for (const row of rows) {
  const [name, currency, price] = row.split(',');
  const code = ISO[name];
  if (!code) throw new Error(`no ISO code for storefront "${name}" — add it to ISO`);
  const amount = Number(price);
  if (!/^[A-Z]{3}$/.test(currency) || !(amount > 0)) {
    throw new Error(`unreadable price row: ${row}`);
  }
  prices[code] = [currency, amount];
}

const lines = Object.keys(prices)
  .sort()
  .map((code) => `  ${code}: ['${prices[code][0]}', ${prices[code][1]}],`)
  .join('\n');

const body = `// GENERATED by scripts/build-prices.mjs from data/app-store-prices.csv —
// do not edit by hand. Yumo Pro's price in each App Store storefront, as
// [ISO 4217 currency, amount], keyed by ISO 3166 country code.
export const APP_STORE_PRICES: Record<string, readonly [string, number]> = {
${lines}
};
`;

writeFileSync(OUT, body, 'utf8');
console.log(`wrote ${Object.keys(prices).length} storefront prices to lib/app-store-prices.ts`);
