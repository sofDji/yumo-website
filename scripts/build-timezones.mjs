// Generates lib/timezones.ts: which country each IANA time zone belongs to.
//
//   npm run build:timezones -- <path to a tzdata zoneinfo directory>
//
// Any tzdata copy works, e.g. Python's `tzdata` package
// (python -c "import tzdata, os; print(os.path.dirname(tzdata.__file__))"
// then append /zoneinfo). The output is committed, so this only needs rerunning
// when a country gains or renames a zone.
//
// The site uses the table to pick the App Store price to show without asking
// any server where the visitor is — see lib/local-price.ts.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../lib/timezones.ts');
const DIR = process.argv[2];
if (!DIR) throw new Error('usage: npm run build:timezones -- <zoneinfo dir>');

// zone.tab names one country per canonical zone. zone1970.tab merges countries
// that have shared clocks since 1970, which is exactly the distinction this
// table needs to keep, so it is not used.
const canonical = new Map();
for (const line of readFileSync(join(DIR, 'zone.tab'), 'utf8').split(/\r?\n/)) {
  if (!line || line.startsWith('#')) continue;
  const [country, , zone] = line.split('\t');
  canonical.set(zone, country);
}

// Browsers still report some legacy names — Chrome says Asia/Calcutta and
// Europe/Kiev. tzdata ships those as copies of the zone they link to, so a
// legacy file is matched to its canonical zone by content, and kept only when
// every identical zone agrees on the country.
const bytes = (zone) => readFileSync(join(DIR, zone)).toString('base64');
const byContent = new Map();
for (const [zone, country] of canonical) {
  const key = bytes(zone);
  byContent.set(key, [...(byContent.get(key) ?? []), country]);
}

function* files(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) yield* files(path);
    else yield relative(DIR, path).replace(/\\/g, '/');
  }
}

const table = new Map(canonical);
for (const zone of files(DIR)) {
  if (table.has(zone) || !zone.includes('/') || /\.(tab|zi)$/.test(zone)) continue;
  if (zone.startsWith('Etc/') || zone.startsWith('posix/') || zone.startsWith('right/')) continue;
  const countries = new Set(byContent.get(bytes(zone)) ?? []);
  if (countries.size === 1) table.set(zone, [...countries][0]);
}

const lines = [...table.keys()]
  .sort()
  .map((zone) => `  '${zone}': '${table.get(zone)}',`)
  .join('\n');

const body = `// GENERATED by scripts/build-timezones.mjs from tzdata's zone.tab — do not
// edit by hand. IANA time zone -> ISO 3166 country code.
export const TIMEZONE_COUNTRY: Record<string, string> = {
${lines}
};
`;

writeFileSync(OUT, body, 'utf8');
console.log(`wrote ${table.size} time zones to lib/timezones.ts`);
